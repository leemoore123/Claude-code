import type { FormSchema, FormField } from '@fsm/shared';

export interface ReportMeta {
  reportTitle: string;
  clientName: string;
  siteName: string;
  jobSummary: string;
  generatedAt: string;
  signatures: { signerRole: string; signerName: string; imagePath?: string | null; signedAt?: string | null }[];
}

function esc(v: unknown): string {
  return String(v ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function renderValue(field: FormField, value: unknown): string {
  if (value === undefined || value === null || value === '') return '<span class="muted">—</span>';
  if (field.type === 'checkbox') return value ? '✓ Yes' : '—';
  if (field.type === 'reading' && field.unit) return `${esc(value)} ${esc(field.unit)}`;
  if (field.type === 'signature' || field.type === 'attachment') return '<span class="muted">(see below)</span>';
  return esc(value);
}

/** Builds a clean, branded HTML report for a completed submission. */
export function buildReportHtml(schema: FormSchema, answers: Record<string, unknown>, meta: ReportMeta): string {
  const sections = schema.sections
    .map((s) => {
      const rows = s.fields
        .filter((f) => f.type !== 'signature')
        .map(
          (f) => `<tr><td class="k">${esc(f.label)}</td><td class="v">${renderValue(f, answers[f.key])}</td></tr>`,
        )
        .join('');
      return `<section><h2>${esc(s.title)}</h2><table class="kv">${rows}</table></section>`;
    })
    .join('');

  const sigs = meta.signatures.length
    ? `<div class="sigs">${meta.signatures
        .map(
          (s) => `<div class="sig">
            <div class="sig-box">${
              s.imagePath ? `<img src="${esc(s.imagePath)}"/>` : '<span class="muted">Not signed</span>'
            }</div>
            <div class="sig-meta"><strong>${esc(s.signerName)}</strong><br/>${esc(s.signerRole)}${
              s.signedAt ? ` · ${esc(new Date(s.signedAt).toLocaleDateString('en-GB'))}` : ''
            }</div>
          </div>`,
        )
        .join('')}</div>`
    : '';

  return `<!doctype html><html><head><meta charset="utf-8"><style>
    * { box-sizing: border-box; }
    body { font-family: 'Helvetica Neue', Arial, sans-serif; color: #0d1b2e; margin: 0; font-size: 12px; }
    .topbar { background: #0d1b2e; color: #fff; padding: 18px 28px; border-bottom: 3px solid #185FA5; display:flex; justify-content:space-between; align-items:center; }
    .brand { font-weight: 700; letter-spacing: .08em; }
    .brand small { color: #9db4d0; font-weight: 400; }
    .doc { padding: 24px 28px; }
    h1 { font-size: 18px; margin: 0 0 4px; }
    .meta { color: #64748b; font-size: 11px; margin-bottom: 18px; }
    .meta b { color: #0d1b2e; }
    section { margin-bottom: 16px; break-inside: avoid; }
    h2 { font-size: 12px; text-transform: uppercase; letter-spacing: .06em; color: #185FA5; border-bottom: 1px solid #e2e8f0; padding-bottom: 4px; margin: 0 0 8px; }
    table.kv { width: 100%; border-collapse: collapse; }
    table.kv td { padding: 4px 8px; border-bottom: 1px solid #f1f5f9; vertical-align: top; }
    td.k { color: #64748b; width: 45%; }
    td.v { font-weight: 500; }
    .muted { color: #94a3b8; }
    .sigs { display: flex; gap: 24px; margin-top: 20px; }
    .sig { flex: 1; }
    .sig-box { height: 70px; border: 1px solid #e2e8f0; border-radius: 6px; display:flex; align-items:center; justify-content:center; }
    .sig-box img { max-height: 64px; max-width: 100%; }
    .sig-meta { font-size: 11px; color: #64748b; margin-top: 6px; }
    .footer { color: #94a3b8; font-size: 10px; margin-top: 24px; border-top: 1px solid #e2e8f0; padding-top: 8px; }
  </style></head><body>
    <div class="topbar">
      <div class="brand">QEY TECHNICAL <small>/ Field Service Management</small></div>
      <div style="font-size:11px;color:#9db4d0">${esc(meta.reportTitle)}</div>
    </div>
    <div class="doc">
      <h1>${esc(schema.title)}</h1>
      <div class="meta">
        <b>${esc(meta.clientName)}</b> · ${esc(meta.siteName)} &nbsp;|&nbsp; ${esc(meta.jobSummary)}<br/>
        Generated ${esc(meta.generatedAt)}
      </div>
      ${sections}
      ${sigs}
      <div class="footer">This report was generated by the QEY FSM platform. Values outside specified pass bands should be reviewed by the responsible engineer.</div>
    </div>
  </body></html>`;
}
